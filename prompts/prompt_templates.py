def build_split_prompt(query):
    return f"""
    你是一个查询分析专家。请分析用户问题是否需要拆解为多个子问题（例如：涉及多个对比对象、多个时间段、或多个并列概念）。
    用户问题："{query}"
    规则：
    1. 如果需要拆分，必须严格按照此格式回答：“拆分为：子问题1 | 子问题2”
    2. 如果不需要拆分，直接回答：“不需要拆分”
    3. 只输出一行结果，不要输出任何其他解释。
    """

def build_multi_query_prompt(q):
    return f"""请针对以下问题生成3个意思相近但表达不同的搜索查询（用于向量数据库检索），每行一个：\n问题：{q}"""


def build_answer_prompt(query: str, context: str) -> str:
    return f"""
        你是一个温柔、耐心、表达清楚的问答助手。

        请根据下面的【检索资料】回答用户的【问题】。

        要求：
        1. 只能依据检索资料回答，不要编造资料中没有的信息。
        2. 如果检索资料中没有足够依据，请明确说明“根据现有资料无法确定”。
        3. 回答要平易近人，但不要改变资料原意。
        4. 尽量用结构清晰的方式回答。

        【检索资料】
        {context}

        【用户问题】
        {query}

        请开始回答：
        """

def build_summary_prompt(messages : str) -> str:
    return f"""请简洁总结以下对话，提取：
        1. 用户关键需求
        2. 已确定的偏好/限制
        3. 重要上下文
        只返回一段总结，不要其他内容。
        对话：
        {messages}"""
        
def build_query_rewrite_prompt(query: str,history_text:str) -> str:
    return f"""
    给你最近的对话历史 + 用户当前的问题
    判断问题里有没有代词（它、这个、那个、上述……）或指代不明的词
    有 → 结合历史把问题改写成一句完整、自包含的问题
    没有 → 原样返回
    只输出改写后的问题，不要解释
    对话历史：{history_text}
    用户问题：{query}
    """
